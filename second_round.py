def group_config(current, group):
    config = deepcopy(current)
    config.update(deepcopy(已测最优))
    config["入场触发口径"] = "LIVE_01"
    for key, value in group[3].items():
        if key in ("开仓条件", "入场约束"):
            config[key].update(deepcopy(value))
        else:
            config[key] = deepcopy(value)
    config["资金约束"].update({"初始资金USDC": 1000., "最小开仓数量ETH": .01, "最大开仓数量ETH": 20.})
    config["成交偏移"] = {"开仓": 0.00005, "平仓": 0.00005}
    config["候选筛选"]["统一目标杠杆"] = 2.
    return config
