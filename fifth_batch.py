def _day_profiles(h,l,c,v,ct,atr):
    days=(ct-1)//86400000;result={}
    for day in np.unique(days):
        idx=np.flatnonzero(days==day)
        if len(idx)!=1440 or ct[idx[0]]!=day*86400000+60000 or ct[idx[-1]]!=(day+1)*86400000:continue
        scale=atr[idx];scale=scale[np.isfinite(scale)]
        if not len(scale):continue
        width=max(float(np.median(scale))*.5,.01);bins=np.floor(c[idx]/width).astype(np.int64);first=int(bins.min());last=int(bins.max())
        if last-first>500000:raise ValueError('第五轮价格轮廓超过50万箱，拒绝无界内存分配')
        weights=np.bincount(bins-first,weights=v[idx],minlength=last-first+1);total=weights.sum();poc=int(np.argmax(weights));lo=hi=poc;kept=weights[poc]
        while kept<.7*total and (lo>0 or hi<len(weights)-1):
            left=weights[lo-1] if lo>0 else -1;right=weights[hi+1] if hi<len(weights)-1 else -1
            if left>=right:lo-=1;kept+=weights[lo]
            else:hi+=1;kept+=weights[hi]
        visits={}
        for j,b in zip(idx,bins):visits.setdefault(int(b),set()).add(int((ct[j]-1)//1800000))
        result[int(day)+1]={'width':width,'first':first,'weights':weights,'total':total,'poc':(first+poc+.5)*width,
                            'val':(first+lo)*width,'vah':(first+hi+1)*width,'visits':visits,'bucket':float(np.median(v[idx]))*20}
