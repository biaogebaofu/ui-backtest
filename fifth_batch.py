@njit(cache=True)
def _ols_slope(x,y,n):
    out=np.full(len(x),np.nan)
    for t in range(n,len(x)):
        a=x[t-n:t];b=y[t-n:t]
        if not np.all(np.isfinite(a)) or not np.all(np.isfinite(b)):continue
        am=np.mean(a);bm=np.mean(b);den=np.sum((a-am)**2)
        if den>1e-20:out[t]=np.sum((a-am)*(b-bm))/den
    return out


