@njit(cache=True)
def _sar_masks(h,l,c):
    """LEAN PSAR无偏移版本的数学递推；两根DM初始化，不交易初始化本身。

    参考：QuantConnect/Lean ParabolicStopAndReverseExtended.cs，2026-09-11读取。
    AF起点/步长=.02，上限=.20；先输出上一迭代已冻结SAR，再更新下一根。
    """
    n=len(c);up=np.zeros(n,np.bool_);dn=up.copy()
    if n<2:return up,dn
    long=not(l[1]<l[0] and h[1]-h[0]<l[0]-l[1]);sar=l[0] if long else h[0];ep=h[1] if long else l[1];af=.02
    for i in range(1,n):
        previous=i if i==1 else i-1;was=long
        if long:
            if l[i]<=sar:
                long=False;sar=max(ep,h[previous],h[i]);out=sar;af=.02;ep=l[i];sar=max(sar+af*(ep-sar),h[previous],h[i])
            else:
                out=sar
                if h[i]>ep:ep=h[i];af=min(.2,af+.02)
                sar=min(sar+af*(ep-sar),l[previous],l[i])
        else:
            if h[i]>=sar:
                long=True;sar=min(ep,l[previous],l[i]);out=sar;af=.02;ep=h[i];sar=min(sar+af*(ep-sar),l[previous],l[i])
            else:
                out=sar
                if l[i]<ep:ep=l[i];af=min(.2,af+.02)
                sar=max(sar+af*(ep-sar),h[previous],h[i])
        if i>1:
            up[i]=not was and long and c[i]>out;dn[i]=was and not long and c[i]<out
    return up,dn


def _line(points):
    times=np.array([p[1] for p in points],dtype=float);values=np.array([p[2] for p in points],dtype=float)
    x=times-times[0];design=np.c_[np.ones(len(x)),x];beta,_,rank,_=np.linalg.lstsq(design,values,rcond=None)
    if rank<2:return None
    intercept=float(beta[0]-beta[1]*times[0]);slope=float(beta[1]);error=float(np.max(np.abs(values-(intercept+slope*times))))
    return intercept,slope,error


