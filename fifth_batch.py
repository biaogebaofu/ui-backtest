@njit(cache=True)
def _ema(x,n,alpha=0.):
    out = np.full(len(x),np.nan); total=0.; count=0; old=np.nan
    if alpha == 0.: alpha=2./(n+1.)
    for i in range(len(x)):
        if not np.isfinite(x[i]): total=0.;count=0;old=np.nan;continue
        if count<n:
            total+=x[i];count+=1
            if count==n: old=total/n;out[i]=old
        else:
            old=alpha*x[i]+(1.-alpha)*old;out[i]=old
    return out


def _rsi(x,n):
    change = np.asarray(x,dtype=float)-_lag(x)
    gain=_ema(np.maximum(change,0),n,1./n);loss=_ema(np.maximum(-change,0),n,1./n)
    total=gain+loss
    return 100*_div(gain,total)


def _wma(x,n):
    if len(x)<n:return np.full(len(x),np.nan)
    weights=np.arange(n,0,-1,dtype=float);weights/=weights.sum()
    return np.r_[np.full(n-1,np.nan),np.convolve(x,weights,'valid')]


def _w4(x): return (x+2*_lag(x)+2*_lag(x,2)+_lag(x,3))/6


def _atr(h,l,c):
    tr=np.maximum(h-l,np.maximum(np.abs(h-_lag(c)),np.abs(l-_lag(c))))
    if len(c): tr[0]=h[0]-l[0]
    return _ema(tr,14,1./14),tr


@njit(cache=True)
def _streak(c):
    out=np.zeros(len(c))
    for i in range(1,len(c)):
        if c[i]>c[i-1]:out[i]=max(out[i-1],0)+1
        elif c[i]<c[i-1]:out[i]=min(out[i-1],0)-1
    return out


@njit(cache=True)
def _recursive(c,h,l,method):
    out=np.full(len(c),np.nan);aux=out.copy()
    if not len(c):return out,aux
    if method==4:
        if len(c)<16:return out,aux
        out[15]=np.mean(c[:16])
        for i in range(16,len(c)):
            n1=(np.max(h[i-15:i-7])-np.min(l[i-15:i-7]))/8
            n2=(np.max(h[i-7:i+1])-np.min(l[i-7:i+1]))/8
            n3=(np.max(h[i-15:i+1])-np.min(l[i-15:i+1]))/16
            if n3<=0 or n1+n2<=0:continue
            d=np.log((n1+n2)/n3)/np.log(2.)
            alpha=min(1.,max(.01,np.exp(-4.6*(d-1))))
            previous=out[i-1] if np.isfinite(out[i-1]) else np.mean(c[i-15:i+1])
            out[i]=alpha*c[i]+(1-alpha)*previous
    elif method==5:
        out[0]=c[0]
        old=c[0];last_reset=0
        for i in range(1,len(c)):
            ratio=c[i]/old if old>0 and np.isfinite(old) else 0.
            denominator=12*ratio**4
            candidate=old+(c[i]-old)/denominator if denominator>1e-20 and np.isfinite(denominator) else np.nan
            if not np.isfinite(candidate) or candidate<=0:
                old=c[i];last_reset=i;continue
            old=candidate
            if i-last_reset>100 or last_reset==0:out[i]=old
    elif method==13:
        out[:min(2,len(c))]=c[:min(2,len(c))]
        a=np.exp(-np.sqrt(2.)*np.pi/20);b=2*a*np.cos(np.sqrt(2.)*np.pi/20);q=1-b+a*a
        for i in range(2,len(c)):out[i]=q*(c[i]+c[i-1])/2+b*out[i-1]-a*a*out[i-2]
    elif method==14:
        old=np.full(4,c[0])
        for i in range(len(c)):
            cur=np.empty(4);cur[0]=.5*c[i]+.5*old[0]
            for j in range(1,4):cur[j]=-.5*cur[j-1]+old[j-1]+.5*old[j]
            cu=0.;cd=0.
            for j in range(3):cu+=max(cur[j]-cur[j+1],0);cd+=max(cur[j+1]-cur[j],0)
            if cu+cd>0:out[i]=cu/(cu+cd)
            aux[i]=cur[0];old=cur
    return out,aux


@njit(cache=True)
def _statistic(x,n,method):
    out=np.full(len(x),np.nan);aux=out.copy()
    for t in range(n-1 if method in (20,21) else n,len(x)):
        window=x[t-n+1:t+1] if method in (20,21) else x[t-n:t]
        if not np.all(np.isfinite(window)):continue
        if method==20:
            vals=np.empty(n*(n-1)//2);at=0
            for i in range(n):
                for j in range(i+1,n):vals[at]=(window[j]-window[i])/(j-i);at+=1
            out[t]=np.quantile(vals,.25);aux[t]=np.quantile(vals,.75)
        elif method==21:
            score=0.;ties=0.
            for i in range(n):
                for j in range(i+1,n):score+=np.sign(window[j]-window[i])
            ordered=np.sort(window);count=1
            for i in range(1,n+1):
                if i<n and ordered[i]==ordered[i-1]:count+=1
                else:ties+=count*(count-1)*(2*count+5);count=1
            var=(n*(n-1)*(2*n+5)-ties)/18
            if var>0:out[t]=(score-np.sign(score))/np.sqrt(var)
        elif method==24:
            pos=0.;neg=0.;runs=0.;last=0.
            for value in window:
                sign=np.sign(value)
                if sign==0:continue
                if sign>0:pos+=1
                else:neg+=1
                if sign!=last:runs+=1
                last=sign
            total=pos+neg
            if total<30 or pos==0 or neg==0:continue
            expected=1+2*pos*neg/total
            var=2*pos*neg*(2*pos*neg-total)/(total*total*(total-1))
            if var>0:out[t]=(runs-expected)/np.sqrt(var)
        elif method==33:
            counts=np.zeros(6)
            for i in range(n-2):
                a=window[i];b=window[i+1];c=window[i+2]
                if a<=b:
                    index=0 if b<=c else (1 if a<=c else 4)
                else:index=2 if a<=c else (3 if b<=c else 5)
                counts[index]+=1
            entropy=0.
            for count in counts:
                if count:pr=count/(n-2);entropy-=pr*np.log(pr)/np.log(6.)
            out[t]=entropy
    return out,aux


