@njit(cache=True)
def _ks(old_new,nold=120,nnew=30):
    out=np.full(len(old_new),np.nan);direction=out.copy()
    for t in range(nold+nnew-1,len(old_new)):
        a=np.sort(old_new[t-nold-nnew+1:t-nnew+1]);b=np.sort(old_new[t-nnew+1:t+1])
        if not np.all(np.isfinite(a)) or not np.all(np.isfinite(b)):continue
        ia=0;ib=0;maximum=0.
        while ia<nold or ib<nnew:
            value=min(a[ia] if ia<nold else np.inf,b[ib] if ib<nnew else np.inf)
            while ia<nold and a[ia]<=value:ia+=1
            while ib<nnew and b[ib]<=value:ib+=1
            maximum=max(maximum,abs(ia/nold-ib/nnew))
        out[t]=maximum;direction[t]=np.median(b)-np.median(a)
    return out,direction


@njit(cache=True)
def _scale_stats(x,method):
    out=np.full(len(x),np.nan)
    n=1024 if method==31 else 512
    for t in range(n-1 if method==31 else n,len(x)):
        if method==31 and (t-(n-1))%20:
            out[t]=out[t-1];continue
        window=x[t-n+1:t+1] if method==31 else x[t-n:t]
        if method==31:
            scales=np.array([4,8,16,32]);logs=np.empty(4);valid=True
            for j in range(4):
                k=scales[j];s=np.std(window[k:]-window[:-k])
                if s<=0:valid=False;break
                logs[j]=np.log(s)
            if valid:
                xs=np.log(scales);xm=np.mean(xs);ym=np.mean(logs)
                out[t]=np.sum((xs-xm)*(logs-ym))/np.sum((xs-xm)**2)
        else:
            variance=np.var(window[1:]-window[:-1])
            if variance<=0:continue
            smallest=np.inf
            for k in (2,4,8):smallest=min(smallest,np.var(window[k:]-window[:-k])/(k*variance))
            out[t]=smallest
    return out


def _endpoint_fit(x,n,degree):
    design=np.vander(np.arange(n,dtype=float),degree+1,increasing=True)
    inv=np.linalg.pinv(design)
    coefficients=[]
    for row in inv:
        coefficients.append(np.r_[np.full(n-1,np.nan),np.convolve(x,row[::-1],'valid')]
                            if len(x)>=n else np.full(len(x),np.nan))
    return coefficients


